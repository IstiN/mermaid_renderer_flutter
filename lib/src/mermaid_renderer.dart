import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:dmtools_mermaid_renderer/src/mermaid_render_options.dart';
import 'package:dmtools_mermaid_renderer/src/svg_normalizer.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:flutter_js/flutter_js.dart';

const bool _kDebugLogs = false;

// ignore: avoid_print
void _log(String msg) {
  if (_kDebugLogs) {
    // ignore: avoid_print
    print('[MermaidRenderer] $msg');
  }
}

/// Dart / Flutter counterpart to the Java {@code MermaidRenderer} class.
///
/// Renders Mermaid diagram DSL to SVG or PNG without a browser:
///
///  * JavaScript engine: flutter_js (QuickJS on Android/Linux, JavaScriptCore
///    on iOS/macOS) — same role as GraalJS in the Java version.
///  * Text metrics: falls back to the built-in JS heuristics inside the bundle
///    (same estimates used when javaMetrics=null in the Java shim).
///  * SVG→PNG: resvg (Rust-based, bundled on macOS) — replaces Apache Batik.
///
/// Typical usage:
///
/// ```dart
/// final renderer = MermaidRenderer();
/// await renderer.init();
///
/// final svg = await renderer.renderToSvg('flowchart TD; A --> B');
/// final png = await renderer.renderToPng('flowchart TD; A --> B');
///
/// renderer.dispose();
/// ```
class MermaidRenderer {
  late final JavascriptRuntime _js;
  bool _initialized = false;

  // Serialise all renders so only one JS polling loop runs at a time.
  // Multiple concurrent loops each call _js.evaluate() every 50 ms which
  // blocks the Dart event loop and causes UI jank.
  Future<void> _renderQueue = Future.value();

  /// Asset path of the mermaid-renderer.js bundle (overridable for testing).
  final String jsAssetPath;

  MermaidRenderer({
    this.jsAssetPath =
        'packages/dmtools_mermaid_renderer/assets/mermaid/mermaid-renderer.js',
  });

  // ─── lifecycle ────────────────────────────────────────────────────────────

  /// Load and evaluate the Mermaid JS bundle.
  ///
  /// Must be called once before [renderToSvg] / [renderToPng].
  /// Safe to call from [WidgetsFlutterBinding.ensureInitialized()] context.
  ///
  /// ⚠️  On desktop platforms (macOS/Windows/Linux) the JS bundle is ~11 MB
  /// and is evaluated synchronously via FFI.  Expect this to block the Dart
  /// event loop for up to a few seconds on the first call.  Call this early
  /// (e.g. at app start) if you want it to complete before the user opens a
  /// markdown panel.
  Future<void> init() async {
    if (_initialized) return;
    _log('init() start');
    _js = getJavascriptRuntime();
    _log('JS runtime created: ${_js.runtimeType}');
    // Yield one frame so the UI is responsive before the heavy sync eval.
    await Future<void>.delayed(Duration.zero);
    final jsSource = await rootBundle.loadString(jsAssetPath);
    _log('JS bundle loaded (${jsSource.length} chars), evaluating...');
    // Yield again after loading so Flutter can process any pending events.
    await Future<void>.delayed(Duration.zero);
    _js.evaluate(jsSource);
    _initialized = true;
    _log('init() complete');
  }

  /// Free the JS runtime resources.
  void dispose() {
    if (_initialized) {
      _js.dispose();
      _initialized = false;
    }
  }

  // ─── public API ───────────────────────────────────────────────────────────

  /// Render [definition] to a normalised SVG string.
  ///
  /// The output is suitable for display with [SvgPicture.string] and opens
  /// correctly in Affinity Designer / Inkscape.
  Future<String> renderToSvg(
    String definition, {
    MermaidRenderOptions? options,
  }) async {
    _assertInitialized();
    // Serialise: chain onto the existing queue using whenComplete so that
    // errors in one render don't poison the queue for subsequent renders.
    final completer = Completer<String>();
    _renderQueue = _renderQueue.whenComplete(() async {
      try {
        final rawSvg = await _jsRender(definition, options?.config);
        completer.complete(SvgNormalizer.normalize(rawSvg));
      } catch (e, st) {
        completer.completeError(e, st);
      }
    });
    return completer.future;
  }

  /// Render [definition] to PNG bytes.
  ///
  /// The PNG is generated by rendering the normalised SVG through the bundled
  /// `resvg` binary (white background, device-pixel resolution = 1).
  ///
  /// Throws [StateError] if `resvg` cannot be found in the app bundle or on
  /// PATH.
  Future<Uint8List> renderToPng(
    String definition, {
    MermaidRenderOptions? options,
  }) async {
    final svg = await renderToSvg(definition, options: options);
    return svgToPng(svg, backgroundColor: options?.backgroundColor);
  }

  // ─── helpers ──────────────────────────────────────────────────────────────

  void _assertInitialized() {
    if (!_initialized) {
      throw StateError(
          'MermaidRenderer not initialised. Call init() before rendering.');
    }
  }

  int _renderCallId = 0;

  Future<String> _jsRender(
    String definition,
    Map<String, Object?>? config,
  ) async {
    // renderMermaidToSvg is an async JS function that internally uses setTimeout
    // and requestAnimationFrame (polyfilled via __dmtoolsTimerQueue).
    // flutter_js has no automatic event loop, so we:
    //   1. Store the resolve/reject value in named globals.
    //   2. Poll every 50 ms, draining __dmtoolsTimerQueue each time, until done.
    //   3. Timeout after 30 s.
    final id = _renderCallId++;
    final svgVar = '__dmtools_r${id}_svg';
    final errVar = '__dmtools_r${id}_err';
    final doneVar = '__dmtools_r${id}_done';

    _log('_jsRender[$id] start, definition length=${definition.length}');
    _js.evaluate('''
      globalThis.$svgVar = undefined;
      globalThis.$errVar = undefined;
      globalThis.$doneVar = false;
      renderMermaidToSvg(${jsonEncode(definition)}, null, ${jsonEncode(config)})
        .then(function(svg) {
          globalThis.$svgVar = svg;
          globalThis.$doneVar = true;
        })
        .catch(function(e) {
          globalThis.$errVar = String(e);
          globalThis.$doneVar = true;
        });
    ''');
    _log('_jsRender[$id] JS kicked off, starting poll...');

    const maxAttempts = 300; // 30 s at 100 ms intervals
    for (var i = 0; i < maxAttempts; i++) {
      await Future<void>.delayed(const Duration(milliseconds: 100));
      // Drain the JS timer / rAF queue so mermaid's async internals can progress.
      _js.evaluate('__dmtoolsDrainTimers();');

      final isDone = _js.evaluate('!!globalThis.$doneVar;').stringResult;
      if (i % 10 == 0) _log('_jsRender[$id] poll attempt $i, isDone=$isDone');
      if (isDone == 'true') {
        final hasErr = _js
            .evaluate(
              'globalThis.$errVar !== undefined;',
            )
            .stringResult;
        if (hasErr == 'true') {
          final err = _js.evaluate('String(globalThis.$errVar);').stringResult;
          _log('_jsRender[$id] FAILED: $err');
          _cleanup(svgVar, errVar, doneVar);
          throw Exception('Mermaid rendering failed: $err');
        }
        final svg = _js.evaluate('String(globalThis.$svgVar);').stringResult;
        _log('_jsRender[$id] SUCCESS, svg length=${svg.length}');
        _cleanup(svgVar, errVar, doneVar);
        return svg;
      }
    }

    _log('_jsRender[$id] TIMEOUT after 30s');
    _cleanup(svgVar, errVar, doneVar);
    throw Exception('Mermaid rendering timed out after 30 s');
  }

  void _cleanup(String svgVar, String errVar, String doneVar) {
    _js.evaluate(
      'delete globalThis.$svgVar;'
      'delete globalThis.$errVar;'
      'delete globalThis.$doneVar;',
    );
  }

  // ─── SVG → PNG conversion (static, reusable) ──────────────────────────────

  /// Optional callback fired whenever a render method is chosen.
  /// Parameters: (method, details).
  /// method is always 'resvg'.
  /// details contains extra info (e.g. path used, error message).
  static void Function(String method, String details)? onRenderMethod;

  /// Convert a normalised SVG string to PNG bytes using the bundled `resvg`
  /// binary.
  ///
  /// The SVG natural [viewBox] / [width] / [height] is used for the output
  /// dimensions.  Supply explicit [width] / [height] to override.
  ///
  /// Throws [StateError] if `resvg` cannot be found in the app bundle or on
  /// PATH.
  static Future<Uint8List> svgToPng(
    String svgString, {
    double? width,
    double? height,
    String? backgroundColor,
  }) async {
    _log(
        'svgToPng() start, svg length=${svgString.length}, width=$width, height=$height');

    final resvgPath = _findResvg();
    _log('svgToPng() using resvg at: $resvgPath');

    final png = await _svgToPngViaResvg(
      svgString,
      resvgPath,
      width,
      height,
      backgroundColor,
    );
    _log('svgToPng() SUCCESS via resvg, png bytes=${png.length}');
    onRenderMethod?.call('resvg', 'path=$resvgPath');
    return png;
  }

  /// Locate the `resvg` binary.
  ///
  /// 1. macOS app bundle: `Contents/Resources/resvg` next to the executable.
  /// 2. Environment variable `RESVG_PATH`.
  /// 3. PATH lookup (`resvg`).
  ///
  /// Throws [StateError] if none of the above yields an executable file.
  static String _findResvg() {
    // 1. macOS bundle relative to resolved executable.
    try {
      final exe = Platform.resolvedExecutable;
      final bundleResvg = File(
        '${File(exe).parent.path}/../Resources/resvg',
      );
      if (bundleResvg.existsSync()) {
        return bundleResvg.path;
      }
    } catch (_) {
      // ignore
    }

    // 2. Explicit override via environment.
    final envPath = Platform.environment['RESVG_PATH'];
    if (envPath != null && File(envPath).existsSync()) {
      return envPath;
    }

    // 3. PATH lookup.
    try {
      final result = Process.runSync('which', ['resvg']);
      if (result.exitCode == 0) {
        final found = result.stdout.toString().trim();
        if (found.isNotEmpty && File(found).existsSync()) {
          return found;
        }
      }
    } catch (_) {
      // ignore
    }

    throw StateError(
      'resvg binary not found. '
      'Expected at \${Bundle}/Contents/Resources/resvg, '
      'or at \$RESVG_PATH, or on PATH.',
    );
  }

  /// Convert SVG to PNG using the `resvg` CLI.
  static Future<Uint8List> _svgToPngViaResvg(
    String svgString,
    String resvgPath,
    double? width,
    double? height,
    String? backgroundColor,
  ) async {
    final tmpSvg = _tmpFile('svg');
    final tmpPng = _tmpFile('png');
    try {
      File(tmpSvg).writeAsStringSync(svgString, encoding: _utf8);

      final args = <String>[
        '--background',
        backgroundColor ?? '#FFFFFF',
        if (width != null) ...['--width', width.toInt().toString()],
        if (height != null) ...['--height', height.toInt().toString()],
        '--quiet',
        tmpSvg,
        tmpPng,
      ];

      _log('_svgToPngViaResvg() running: $resvgPath ${args.join(" ")}');
      final result = await Process.run(resvgPath, args);

      if (result.exitCode != 0) {
        final err = result.stderr.toString();
        _log('_svgToPngViaResvg() resvg failed: $err');
        throw StateError('resvg failed (exit ${result.exitCode}): $err');
      }

      final png = File(tmpPng);
      if (!png.existsSync()) {
        throw StateError('resvg produced no output file at $tmpPng');
      }
      return png.readAsBytesSync();
    } finally {
      _tryDelete(tmpSvg);
      _tryDelete(tmpPng);
    }
  }

  static String _tmpFile(String ext) =>
      '${Directory.systemTemp.path}/dmtools_mermaid_${DateTime.now().microsecondsSinceEpoch}.$ext';

  static void _tryDelete(String path) {
    try {
      File(path).deleteSync();
    } catch (_) {}
  }

  static const Utf8Codec _utf8 = Utf8Codec();
}
